#!/usr/bin/env bash
# ╔══════════════════════════════════════════════════════╗
# ║   netmon — install script                            ║
# ║   Creates a global `netmon` command                  ║
# ╚══════════════════════════════════════════════════════╝
set -e

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VENV_DIR="$REPO_DIR/.venv"
INSTALL_DIR="$HOME/.local/bin"
LAUNCHER="$INSTALL_DIR/netmon"
EXPAT_LIB="/opt/homebrew/opt/expat/lib"

# ── macOS: Homebrew Python needs Homebrew libexpat at runtime ─
setup_dyld() {
    if [[ "$(uname -s)" == Darwin ]] && [[ -d "$EXPAT_LIB" ]]; then
        export DYLD_LIBRARY_PATH="${EXPAT_LIB}${DYLD_LIBRARY_PATH:+:$DYLD_LIBRARY_PATH}"
    fi
}

python_ok() {
    "$1" -c "import xml.parsers.expat" &>/dev/null
}

find_python() {
    local candidates=(
        python3.13
        python3.12
        python3.11
        /opt/homebrew/bin/python3.13
        /opt/homebrew/bin/python3.12
        python3
    )
    local py
    for py in "${candidates[@]}"; do
        if command -v "$py" &>/dev/null && python_ok "$py"; then
            command -v "$py"
            return 0
        fi
    done
    return 1
}

setup_dyld

# ── 1. Python check ───────────────────────────────────────────
PYTHON="$(find_python)" || {
    echo "❌  No working Python 3.8+ found."
    echo "    Homebrew Pythons often need: brew install expat"
    echo "    Or reinstall: brew reinstall python@3.13"
    exit 1
}

PYVER=$("$PYTHON" -c 'import sys; print(f"{sys.version_info.major}.{sys.version_info.minor}")')
PYMAJ=$("$PYTHON" -c 'import sys; print(sys.version_info.major)')
PYMIN=$("$PYTHON" -c 'import sys; print(sys.version_info.minor)')
if [ "$PYMAJ" -lt 3 ] || { [ "$PYMAJ" -eq 3 ] && [ "$PYMIN" -lt 8 ]; }; then
    echo "❌  Python 3.8+ required (found $PYVER)"
    exit 1
fi
echo "✓  Python $PYVER ($PYTHON)"

# ── 2. Virtual environment ────────────────────────────────────
if [ -d "$VENV_DIR" ] && ! python_ok "$VENV_DIR/bin/python"; then
    echo "   Removing broken virtual environment..."
    rm -rf "$VENV_DIR"
fi

if [ ! -d "$VENV_DIR" ]; then
    echo "   Creating virtual environment..."
    "$PYTHON" -m venv "$VENV_DIR"
fi
echo "✓  Virtual environment at $VENV_DIR"

# ── 3. Dependencies ───────────────────────────────────────────
echo "   Installing dependencies..."
"$VENV_DIR/bin/pip" install --upgrade pip -q
"$VENV_DIR/bin/pip" install -e "$REPO_DIR" -q
echo "✓  Dependencies installed"

# ── 4. Global launcher ───────────────────────────────────────
mkdir -p "$INSTALL_DIR"

DYLD_SNIPPET=""
if [[ "$(uname -s)" == Darwin ]] && [[ -d "$EXPAT_LIB" ]]; then
    DYLD_SNIPPET="export DYLD_LIBRARY_PATH=\"${EXPAT_LIB}\${DYLD_LIBRARY_PATH:+:\$DYLD_LIBRARY_PATH}\""
fi

cat > "$LAUNCHER" << LAUNCHER_EOF
#!/usr/bin/env bash
# netmon global launcher — auto-generated by install.sh
$DYLD_SNIPPET
source "$VENV_DIR/bin/activate"
cd "$REPO_DIR"
exec python -m netmon "\$@"
LAUNCHER_EOF
chmod +x "$LAUNCHER"
echo "✓  Launcher created at $LAUNCHER"

# ── 5. PATH setup ────────────────────────────────────────────
SHELL_RC=""
if [ -f "$HOME/.zshrc" ]; then
    SHELL_RC="$HOME/.zshrc"
elif [ -f "$HOME/.bashrc" ]; then
    SHELL_RC="$HOME/.bashrc"
fi

if [[ ":$PATH:" != *":$INSTALL_DIR:"* ]]; then
    if [ -n "$SHELL_RC" ]; then
        echo "" >> "$SHELL_RC"
        echo "# netmon — added by install.sh" >> "$SHELL_RC"
        echo 'export PATH="$HOME/.local/bin:$PATH"' >> "$SHELL_RC"
        echo "✓  Added $INSTALL_DIR to PATH in $SHELL_RC"
        echo ""
        echo "   ⚠  Reload your shell:  source $SHELL_RC"
    else
        echo "⚠  Add $INSTALL_DIR to your PATH manually."
    fi
else
    echo "✓  $INSTALL_DIR already in PATH"
fi

# ── Done ──────────────────────────────────────────────────────
echo ""
echo "╔══════════════════════════════════════╗"
echo "║   netmon installed successfully!     ║"
echo "╚══════════════════════════════════════╝"
echo ""
echo "   Run:    netmon"
echo "   Quit:   q"
echo "   Help:   ?  (inside the app)"
echo ""
